import { useState, useEffect } from "react";
import { Dialog } from "../../../components/ui/Dialog";
import { Button } from "../../../components/ui/Button";
import { formatCurrency } from "../../../lib/formatters";
import { PaymentRow } from "../../../api/payments";
import {
  ShieldCheck,
  CheckCircle2,
  XCircle,
  Copy,
  Download,
  RotateCcw,
  Info,
  Clock,
  Landmark,
} from "lucide-react";
import { AvartaCrest } from "../../../components/brand/AvartaCrest";
import { useAuth } from "../../../app/AuthContext";

export interface DisbursementModalProps {
  isOpen: boolean;
  onClose: () => void;
  selectedPayments: PaymentRow[];
  totalAmount: number;
  currency: string;
  onConfirmDisburse: () => Promise<PaymentRow | null>;
  isExecuting?: boolean;
}

type ModalLifecycle = "CONFIGURING" | "PROCESSING" | "SUCCESS" | "FAILED";

interface SettlementReceipt {
  reference: string;
  timestamp: string;
  method: string;
  amount: number;
  currency: string;
  utrNumber: string | null;
  clearingDate: string | null;
  clearingDocumentNumber: string | null;
  bankConfirmed: boolean;
}

function formatReceiptTimestamp(value: string | null | undefined): string {
  if (!value) return "—";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return value;
  return date.toLocaleString("en-IN", {
    day: "2-digit",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
  });
}

export function DisbursementModal({
  isOpen,
  onClose,
  selectedPayments,
  totalAmount,
  currency,
  onConfirmDisburse,
  isExecuting = false,
}: DisbursementModalProps) {
  const { user } = useAuth();
  const isSingle = selectedPayments.length === 1;
  const singlePayment = isSingle ? selectedPayments[0] : null;

  const [lifecycle, setLifecycle] = useState<ModalLifecycle>("CONFIGURING");
  const [errorMessage, setErrorMessage] = useState<string>("");
  const [copiedRef, setCopiedRef] = useState(false);
  const [receipt, setReceipt] = useState<SettlementReceipt | null>(null);

  useEffect(() => {
    if (isOpen) {
      setLifecycle("CONFIGURING");
      setErrorMessage("");
      setCopiedRef(false);
      setReceipt(null);
    }
  }, [isOpen]);

  async function handleDisburse() {
    setLifecycle("PROCESSING");
    setErrorMessage("");

    try {
      const executed = await onConfirmDisburse();
      const confirmed = executed?.utrNumber != null && executed?.clearingDate != null;
      setReceipt({
        reference: executed?.id ?? selectedPayments[0]?.id ?? "—",
        timestamp: formatReceiptTimestamp(
          executed?.clearingDate ?? new Date().toISOString()
        ),
        method: executed?.method ?? singlePayment?.method ?? "Configured payment route",
        amount: totalAmount,
        currency,
        utrNumber: executed?.utrNumber ?? null,
        clearingDate: executed?.clearingDate ?? null,
        clearingDocumentNumber: executed?.clearingDocumentNumber ?? null,
        bankConfirmed: confirmed,
      });
      setLifecycle("SUCCESS");
    } catch (err: unknown) {
      setErrorMessage(
        err instanceof Error ? err.message : "The payment could not be executed."
      );
      setLifecycle("FAILED");
    }
  }

  function handleCopyReference() {
    if (!receipt) return;
    void navigator.clipboard?.writeText(receipt.reference);
    setCopiedRef(true);
    setTimeout(() => setCopiedRef(false), 2000);
  }

  function handleDownloadPaymentAdvice() {
    if (!receipt) return;
    const adviceText = [
      "================================================================================",
      "          AVARTA AP WORKSPACE — PAYMENT EXECUTION ADVICE",
      "================================================================================",
      `SETTLEMENT REFERENCE : ${receipt.reference}`,
      `TRANSACTION STATUS   : ${receipt.bankConfirmed ? "CONFIRMED BY PAYMENT ROUTE" : "RECORDED — BANK CONFIRMATION PENDING"}`,
      `BANK UTR NUMBER      : ${receipt.utrNumber ?? "Pending"}`,
      `BANK CLEARING DATE   : ${receipt.clearingDate ?? "Pending"}`,
      `ERP CLEARING DOC REF : ${receipt.clearingDocumentNumber ?? "Pending ERP sync"}`,
      `EXECUTION TIMESTAMP  : ${receipt.timestamp}`,
      `SETTLEMENT ROUTE     : ${receipt.method}`,
      `TOTAL DEBIT AMOUNT   : ${receipt.currency} ${receipt.amount.toFixed(2)}`,
      `ORGANIZATION ID      : ${user?.organizationId ?? "—"}`,
      "================================================================================",
      "ITEMIZED INVOICES:",
      ...selectedPayments.map(
        (p, idx) =>
          `${idx + 1}. ${p.invoiceNumber} | ${p.vendor} | ${p.currency} ${p.amount}`
      ),
      "================================================================================",
      "Generated by Avarta AP Workspace. Identifiers are taken from the",
      "server-confirmed payment record; missing values are shown as Pending.",
    ].join("\n");

    const blob = new Blob([adviceText], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const anchor = document.createElement("a");
    anchor.href = url;
    anchor.download = `Payment_Advice_${receipt.reference}.txt`;
    anchor.click();
    URL.revokeObjectURL(url);
  }

  const busy = lifecycle === "PROCESSING" || isExecuting;

  return (
    <Dialog
      isOpen={isOpen}
      onClose={busy ? () => undefined : onClose}
      size="2xl"
      title={
        lifecycle === "SUCCESS"
          ? "Payment Execution Recorded"
          : lifecycle === "FAILED"
            ? "Payment Execution Failed"
            : isSingle
              ? "Authorize Payment Execution"
              : "Authorize Batch Payment Execution"
      }
      description={
        lifecycle === "SUCCESS"
          ? `Server-confirmed execution for ${selectedPayments.length} invoice(s).`
          : lifecycle === "FAILED"
            ? "No payment was marked as paid. Resolve the error and retry."
            : isSingle
              ? `Execute payment for Invoice ${singlePayment?.invoiceNumber} (${singlePayment?.vendor}).`
              : `Execute ${selectedPayments.length} approved invoices through the configured payment route.`
      }
    >
      <div className="space-y-4 pt-1 flex-1 overflow-y-auto pr-1">
        {lifecycle === "SUCCESS" && receipt && (
          <div className="space-y-4">
            <div className="p-4 rounded-lg bg-emerald-50 dark:bg-emerald-950/40 border border-emerald-200 dark:border-emerald-900/80 flex items-start gap-3.5">
              <div className="w-10 h-10 rounded-full bg-emerald-100 dark:bg-emerald-900/60 text-emerald-600 dark:text-emerald-400 flex items-center justify-center shrink-0 mt-0.5">
                <CheckCircle2 size={24} />
              </div>
              <div className="space-y-1">
                <h4 className="text-body font-bold text-emerald-950 dark:text-emerald-100">
                  {receipt.bankConfirmed
                    ? "Payment Confirmed by the Payment Route"
                    : "Payment Recorded — Awaiting Bank Confirmation"}
                </h4>
                <p className="text-caption text-emerald-800 dark:text-emerald-300">
                  {receipt.bankConfirmed
                    ? "The payment route returned a bank UTR and clearing date. Ledgers are updated to PAID."
                    : "The workspace has marked the payment PAID. Bank identifiers will appear once the route confirms settlement."}
                </p>
              </div>
            </div>

            <div className="relative p-4 rounded-xl border border-neutral-200 dark:border-zinc-800 bg-neutral-50/70 dark:bg-zinc-900/60 space-y-3 font-mono overflow-hidden">
              <AvartaCrest variant="watermark" className="opacity-[0.04] dark:opacity-[0.05]" />

              <div className="relative z-10 flex items-center justify-between border-b border-neutral-200 dark:border-zinc-800 pb-2.5">
                <div className="flex items-center gap-2.5">
                  <div className="w-8 h-8 rounded-lg bg-neutral-100 dark:bg-zinc-800 border border-neutral-200/80 dark:border-zinc-700/80 flex items-center justify-center p-0.5">
                    <AvartaCrest variant="shield" glow className="w-full h-full" />
                  </div>
                  <div>
                    <span className="font-semibold text-body-sm text-neutral-900 dark:text-zinc-100 block font-sans">
                      Avarta Payment Execution Advice
                    </span>
                    <span className="text-[10px] text-neutral-500 dark:text-zinc-400">
                      Server-confirmed execution record
                    </span>
                  </div>
                </div>
                <span className="text-micro font-mono font-semibold text-emerald-700 dark:text-emerald-300 bg-emerald-100/70 dark:bg-emerald-950/60 px-2 py-0.5 rounded border border-emerald-300 dark:border-emerald-800">
                  {receipt.bankConfirmed ? "CONFIRMED" : "PENDING CONFIRMATION"}
                </span>
              </div>

              <div className="relative z-10 flex items-center justify-between border-b border-neutral-200/60 dark:border-zinc-800/60 pb-2.5">
                <div className="space-y-0.5">
                  <span className="text-micro text-neutral-400 dark:text-zinc-500 uppercase tracking-wider block">
                    Payment Reference
                  </span>
                  <div className="flex items-center gap-2">
                    <span className="text-body font-bold text-neutral-900 dark:text-zinc-100 break-all">
                      {receipt.reference}
                    </span>
                    <button
                      type="button"
                      onClick={handleCopyReference}
                      className="inline-flex items-center gap-1 text-micro text-indigo-600 dark:text-indigo-400 hover:underline font-sans"
                    >
                      <Copy size={12} />
                      <span>{copiedRef ? "Copied!" : "Copy"}</span>
                    </button>
                  </div>
                </div>
                <div className="text-right space-y-0.5">
                  <span className="text-micro text-neutral-400 dark:text-zinc-500 uppercase tracking-wider block">
                    Execution Timestamp
                  </span>
                  <span className="text-caption text-neutral-700 dark:text-zinc-300">
                    {receipt.timestamp}
                  </span>
                </div>
              </div>

              <div className="relative z-10 grid grid-cols-2 sm:grid-cols-3 gap-3 text-caption pt-1">
                <div>
                  <span className="text-micro text-neutral-400 dark:text-zinc-500 uppercase block">
                    Total Debited
                  </span>
                  <span className="text-body-sm font-bold text-emerald-700 dark:text-emerald-400 tabular-nums">
                    {formatCurrency(receipt.amount, receipt.currency)}
                  </span>
                </div>
                <div>
                  <span className="text-micro text-neutral-400 dark:text-zinc-500 uppercase block">
                    Payment Route
                  </span>
                  <span className="text-neutral-800 dark:text-zinc-200 font-medium">
                    {receipt.method}
                  </span>
                </div>
                <div>
                  <span className="text-micro text-neutral-400 dark:text-zinc-500 uppercase block">
                    Bank UTR Number
                  </span>
                  <span className="text-emerald-700 dark:text-emerald-400 font-mono font-semibold text-caption truncate block">
                    {receipt.utrNumber ?? "Pending"}
                  </span>
                </div>
                <div>
                  <span className="text-micro text-neutral-400 dark:text-zinc-500 uppercase block">
                    Clearing Date
                  </span>
                  <span className="text-neutral-800 dark:text-zinc-200 font-medium font-mono text-caption">
                    {receipt.clearingDate ?? "Pending"}
                  </span>
                </div>
                <div>
                  <span className="text-micro text-neutral-400 dark:text-zinc-500 uppercase block">
                    ERP Clearing Doc
                  </span>
                  <span className="text-neutral-800 dark:text-zinc-200 font-medium font-mono text-caption">
                    {receipt.clearingDocumentNumber ?? "Pending ERP sync"}
                  </span>
                </div>
              </div>

              <div className="pt-2 border-t border-neutral-200/60 dark:border-zinc-800/60 text-micro">
                <span className="text-neutral-400 dark:text-zinc-500 uppercase tracking-wider block mb-1">
                  Executed Invoices ({selectedPayments.length})
                </span>
                <div className="space-y-1">
                  {selectedPayments.map((p) => (
                    <div
                      key={p.id}
                      className="flex items-center justify-between text-neutral-700 dark:text-zinc-300"
                    >
                      <span>
                        {p.invoiceNumber} • {p.vendor}
                      </span>
                      <span className="font-semibold tabular-nums">
                        {formatCurrency(p.amount, p.currency ?? currency)}
                      </span>
                    </div>
                  ))}
                </div>
              </div>
            </div>

            <div className="flex items-center justify-between text-micro font-mono text-neutral-400 dark:text-zinc-500 pt-1 border-t border-neutral-100 dark:border-zinc-800">
              <span className="flex items-center gap-1.5">
                <ShieldCheck size={14} className="text-emerald-500" />
                <span>Executed with a server-confirmed idempotency key</span>
              </span>
              <span className="text-emerald-600 dark:text-emerald-400 font-semibold">
                Ledgers Updated
              </span>
            </div>

            <div className="flex items-center justify-end gap-3 pt-2 border-t border-neutral-200 dark:border-zinc-800">
              <Button
                type="button"
                variant="outline"
                onClick={handleDownloadPaymentAdvice}
                className="gap-2"
              >
                <Download size={14} />
                <span>Download Payment Advice</span>
              </Button>
              <Button
                type="button"
                onClick={onClose}
                className="bg-emerald-600 hover:bg-emerald-500 text-white font-semibold"
              >
                Done &amp; Return to Payments
              </Button>
            </div>
          </div>
        )}

        {lifecycle === "FAILED" && (
          <div className="space-y-4">
            <div className="p-4 rounded-lg bg-red-50 dark:bg-red-950/40 border border-red-200 dark:border-red-900/80 flex items-start gap-3.5">
              <div className="w-10 h-10 rounded-full bg-red-100 dark:bg-red-900/60 text-red-600 dark:text-red-400 flex items-center justify-center shrink-0 mt-0.5">
                <XCircle size={24} />
              </div>
              <div className="space-y-1">
                <h4 className="text-body font-bold text-red-950 dark:text-red-100">
                  Payment Execution Failed
                </h4>
                <p className="text-caption text-red-800 dark:text-red-300 leading-relaxed">
                  {errorMessage || "The payment could not be executed."}
                </p>
              </div>
            </div>

            <div className="p-4 rounded-lg border border-neutral-200 dark:border-zinc-800 bg-neutral-50/70 dark:bg-zinc-900/60 space-y-2 text-caption">
              <div className="flex items-center justify-between text-neutral-500 border-b border-neutral-200 dark:border-zinc-800 pb-2">
                <span className="font-semibold uppercase text-micro">Retry Safety</span>
                <span className="text-red-600 dark:text-red-400 font-semibold">
                  NO PAYMENT MARKED PAID
                </span>
              </div>
              <p className="text-micro text-neutral-600 dark:text-zinc-300">
                The server rejected the execution, so no invoice was moved to PAID. Retrying reuses
                the same idempotency key for this modal session and cannot double-debit.
              </p>
              <div className="flex items-center justify-between">
                <span className="text-neutral-400">Pending Amount:</span>
                <span className="font-bold font-mono">
                  {formatCurrency(totalAmount, currency)}
                </span>
              </div>
            </div>

            <div className="flex items-center justify-between pt-2 border-t border-neutral-200 dark:border-zinc-800">
              <Button
                type="button"
                variant="outline"
                onClick={() => setLifecycle("CONFIGURING")}
                className="gap-1.5 text-caption font-medium"
              >
                <span>Review Batch</span>
              </Button>
              <div className="flex items-center gap-2.5">
                <Button type="button" variant="outline" onClick={onClose}>
                  Cancel
                </Button>
                <Button
                  onClick={handleDisburse}
                  disabled={busy}
                  className="gap-2 bg-indigo-600 hover:bg-indigo-500 text-white font-semibold"
                >
                  <RotateCcw size={14} />
                  <span>Retry Execution</span>
                </Button>
              </div>
            </div>
          </div>
        )}

        {lifecycle === "CONFIGURING" && (
          <>
            <div className="p-3 rounded-lg bg-neutral-50 dark:bg-zinc-800/50 border border-neutral-200 dark:border-zinc-800 flex items-start gap-2.5 text-caption">
              <Landmark size={16} className="text-indigo-600 dark:text-indigo-400 shrink-0 mt-0.5" />
              <div className="space-y-0.5">
                <p className="font-semibold text-neutral-900 dark:text-zinc-100">
                  Configured payment route
                </p>
                <p className="text-micro text-neutral-600 dark:text-zinc-300">
                  Execution uses the payment gateway or manual bank-transfer configuration in
                  Settings → Integrations. Change it there before executing; this dialog cannot
                  override treasury routing.
                </p>
              </div>
            </div>

            <div className="border border-neutral-200 dark:border-zinc-800 rounded-lg overflow-hidden">
              <div className="bg-neutral-50 dark:bg-zinc-800/60 px-3 py-2 text-micro font-semibold uppercase tracking-wider text-neutral-500 dark:text-zinc-400 flex items-center justify-between">
                <span>Invoices in this execution</span>
                <span>{selectedPayments.length}</span>
              </div>
              <div className="divide-y divide-neutral-100 dark:divide-zinc-800 max-h-56 overflow-y-auto">
                {selectedPayments.map((p) => (
                  <div key={p.id} className="px-3 py-2.5 flex items-center justify-between gap-3 text-caption">
                    <div className="min-w-0">
                      <span className="font-mono font-semibold text-neutral-900 dark:text-zinc-100">
                        {p.invoiceNumber}
                      </span>
                      <span className="text-neutral-500 dark:text-zinc-400"> • {p.vendor}</span>
                    </div>
                    <span className="font-mono tabular-nums font-semibold text-neutral-900 dark:text-zinc-100 shrink-0">
                      {formatCurrency(p.amount, p.currency ?? currency)}
                    </span>
                  </div>
                ))}
              </div>
              <div className="px-3 py-2.5 border-t border-neutral-200 dark:border-zinc-800 bg-neutral-50 dark:bg-zinc-800/40 flex items-center justify-between text-body-sm">
                <span className="font-semibold text-neutral-700 dark:text-zinc-300">Total debit</span>
                <span className="font-mono font-bold tabular-nums text-neutral-900 dark:text-zinc-100">
                  {formatCurrency(totalAmount, currency)}
                </span>
              </div>
            </div>

            <div className="p-3 rounded-lg bg-amber-50 dark:bg-amber-950/30 border border-amber-200 dark:border-amber-900/70 flex items-start gap-2 text-caption text-amber-800 dark:text-amber-300">
              <Info size={15} className="shrink-0 mt-0.5" />
              <div className="flex items-center gap-1.5 text-micro">
                <Clock size={12} />
                <span>
                  Execution is final and requires server confirmation. Do not close this dialog
                  while the request is in flight.
                </span>
              </div>
            </div>

            <div className="flex items-center justify-end gap-2.5 pt-2 border-t border-neutral-200 dark:border-zinc-800">
              <Button type="button" variant="outline" onClick={onClose} disabled={busy}>
                Cancel
              </Button>
              <Button
                onClick={handleDisburse}
                disabled={busy || selectedPayments.length === 0}
                className="gap-2 bg-indigo-600 hover:bg-indigo-500 text-white font-semibold"
              >
                <ShieldCheck size={15} />
                <span>{busy ? "Executing…" : isSingle ? "Execute Payment" : "Execute Batch"}</span>
              </Button>
            </div>
          </>
        )}

        {lifecycle === "PROCESSING" && (
          <div className="space-y-4 py-8 text-center">
            <div className="w-12 h-12 rounded-full bg-indigo-50 dark:bg-indigo-950/60 text-indigo-600 dark:text-indigo-400 mx-auto flex items-center justify-center">
              <Clock size={24} className="animate-pulse" />
            </div>
            <h4 className="text-body font-semibold text-neutral-900 dark:text-zinc-100">
              Executing payment through the configured route…
            </h4>
            <p className="text-caption text-neutral-500 dark:text-zinc-400">
              Waiting for server confirmation. No optimistic ledger update has been applied.
            </p>
          </div>
        )}
      </div>
    </Dialog>
  );
}
