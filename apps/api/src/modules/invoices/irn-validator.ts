import crypto from "crypto";

/**
 * e-Invoice IRN & Signed QR Code Validation (T-504)
 * Aligned with Indian GST Rules (Rule 48(4) of CGST Rules 2017) and NIC e-Invoice System Specs.
 */

export interface EInvoiceQrPayload {
  Irn?: string;
  irn?: string;
  SellerGstin?: string;
  sellerGstin?: string;
  BuyerGstin?: string;
  buyerGstin?: string;
  DocNo?: string;
  docNo?: string;
  DocTyp?: string;
  docTyp?: string;
  DocDt?: string;
  docDt?: string;
  TotInvVal?: number;
  totInvVal?: number;
  ItemCnt?: number;
  itemCnt?: number;
  MainHsnCode?: string;
  mainHsnCode?: string;
  IrnDt?: string;
  irnDt?: string;
  [key: string]: unknown;
}

export interface NormalizedQrPayload {
  irn: string;
  sellerGstin: string;
  buyerGstin: string;
  docNo: string;
  docTyp: string;
  docDt: string;
  totalValue: number;
  itemCount?: number;
  mainHsnCode?: string;
}

export interface EInvoiceValidationResult {
  isValid: boolean;
  isMandatory: boolean;
  irn: string | null;
  qrVerified: boolean;
  discrepancies: string[];
}

/**
 * Statutory e-invoicing turnover threshold in India under Notification No. 10/2023-CT:
 * ₹5 Crore (₹50,000,000) aggregate annual turnover.
 */
export const STATUTORY_EINVOICE_TURNOVER_THRESHOLD_INR = 50000000;

/**
 * Validates whether an Invoice Reference Number (IRN) conforms to statutory 64-character hex format.
 * Format: 64 hexadecimal characters (SHA-256 hash generated by IRP).
 */
export function validateIrnFormat(irn: string | null | undefined): boolean {
  if (!irn || typeof irn !== "string") return false;
  return /^[a-f0-9]{64}$/i.test(irn.trim());
}

/**
 * Computes official NIC e-Invoice IRN hash (SHA-256 of Supplier GSTIN + FY + DocType + DocNo).
 * Standard Doc Types: "INV" (Tax Invoice), "CRN" (Credit Note), "DBN" (Debit Note).
 * FY format: "2024-25" or "2025-26".
 */
export function computeIrnHash(
  supplierGstin: string,
  financialYear: string,
  docType: string,
  docNumber: string
): string {
  const cleanGstin = supplierGstin.trim().toUpperCase();
  const cleanFy = financialYear.trim();
  const cleanType = docType.trim().toUpperCase();
  const cleanDoc = docNumber.trim();
  const rawString = `${cleanGstin}${cleanFy}${cleanType}${cleanDoc}`;
  return crypto.createHash("sha256").update(rawString).digest("hex").toLowerCase();
}

/**
 * Parses e-Invoice Signed QR code.
 * Standard IRP QR is a signed JWT (3 base64url parts) or a JSON payload.
 */
export function parseSignedQrCode(qrPayload: string | null | undefined): NormalizedQrPayload | null {
  if (!qrPayload || typeof qrPayload !== "string") return null;

  const trimmed = qrPayload.trim();

  try {
    // 1. Try parsing as JWT (header.payload.signature)
    if (trimmed.includes(".")) {
      const parts = trimmed.split(".");
      if (parts.length >= 2) {
        const payloadBase64 = parts[1].replace(/-/g, "+").replace(/_/g, "/");
        const padded = payloadBase64.padEnd(
          payloadBase64.length + ((4 - (payloadBase64.length % 4)) % 4),
          "="
        );
        const jsonStr = Buffer.from(padded, "base64").toString("utf-8");
        const parsed = JSON.parse(jsonStr) as EInvoiceQrPayload;
        return normalizeQrPayload(parsed);
      }
    }

    // 2. Try parsing as direct JSON
    if (trimmed.startsWith("{") && trimmed.endsWith("}")) {
      const parsed = JSON.parse(trimmed) as EInvoiceQrPayload;
      return normalizeQrPayload(parsed);
    }
  } catch {
    return null;
  }

  return null;
}

function normalizeQrPayload(raw: EInvoiceQrPayload): NormalizedQrPayload {
  const irn = String(raw.Irn || raw.irn || "").trim().toLowerCase();
  const sellerGstin = String(raw.SellerGstin || raw.sellerGstin || "").trim().toUpperCase();
  const buyerGstin = String(raw.BuyerGstin || raw.buyerGstin || "").trim().toUpperCase();
  const docNo = String(raw.DocNo || raw.docNo || "").trim();
  const docTyp = String(raw.DocTyp || raw.docTyp || "INV").trim().toUpperCase();
  const docDt = String(raw.DocDt || raw.docDt || "").trim();
  const totalValue = Number(raw.TotInvVal ?? raw.totInvVal ?? 0);
  const itemCount = raw.ItemCnt != null ? Number(raw.ItemCnt) : raw.itemCnt != null ? Number(raw.itemCnt) : undefined;
  const mainHsnCode = raw.MainHsnCode ? String(raw.MainHsnCode) : raw.mainHsnCode ? String(raw.mainHsnCode) : undefined;

  return {
    irn,
    sellerGstin,
    buyerGstin,
    docNo,
    docTyp,
    docDt,
    totalValue,
    itemCount,
    mainHsnCode,
  };
}

/**
 * Validates e-Invoice IRN and Signed QR Code for an invoice.
 */
export function validateEInvoice(params: {
  invoiceNumber: string;
  totalAmount: number;
  irn?: string | null;
  signedQrCode?: string | null;
  supplierGstin?: string | null;
  buyerGstin?: string | null;
  supplierTurnover?: number | null;
  isSupplierEInvoicingApplicable?: boolean | null;
  turnoverThreshold?: number;
  tolerance?: number;
}): EInvoiceValidationResult {
  const discrepancies: string[] = [];
  const threshold = params.turnoverThreshold ?? STATUTORY_EINVOICE_TURNOVER_THRESHOLD_INR;
  const tolerance = params.tolerance ?? 1.0;

  // Determine if e-invoicing is statutory requirement for this supplier
  const isMandatory = Boolean(
    params.isSupplierEInvoicingApplicable ||
      (params.supplierTurnover != null && params.supplierTurnover >= threshold)
  );

  const cleanIrn = (params.irn || "").trim().toLowerCase();

  // 1. Mandatory e-invoicing check
  if (isMandatory && !cleanIrn) {
    discrepancies.push(
      `Supplier has annual turnover >= ₹5 Cr (mandatory e-invoicing under Rule 48(4)), but invoice lacks a 64-character IRN.`
    );
  }

  // 2. Format validation (if IRN provided)
  if (cleanIrn) {
    if (!validateIrnFormat(cleanIrn)) {
      discrepancies.push(
        `Invalid IRN format: "${cleanIrn}". Must be exactly 64 hexadecimal characters.`
      );
    }
  }

  // 3. Signed QR Code payload verification
  let qrVerified = false;
  if (params.signedQrCode) {
    const qrData = parseSignedQrCode(params.signedQrCode);
    if (!qrData) {
      discrepancies.push("Signed QR code is malformed or could not be decoded.");
    } else {
      qrVerified = true;

      // Verify QR payload IRN matches header IRN
      if (cleanIrn && qrData.irn && cleanIrn !== qrData.irn) {
        discrepancies.push(
          `QR code IRN mismatch: QR contains "${qrData.irn}", but invoice header has "${cleanIrn}".`
        );
      }

      // Verify Supplier GSTIN
      if (params.supplierGstin) {
        const expectedGstin = params.supplierGstin.trim().toUpperCase();
        if (qrData.sellerGstin && qrData.sellerGstin !== expectedGstin) {
          discrepancies.push(
            `QR code Seller GSTIN mismatch: QR contains "${qrData.sellerGstin}", expected "${expectedGstin}".`
          );
        }
      }

      // Verify Buyer GSTIN
      if (params.buyerGstin && qrData.buyerGstin) {
        const expectedBuyer = params.buyerGstin.trim().toUpperCase();
        if (qrData.buyerGstin !== expectedBuyer) {
          discrepancies.push(
            `QR code Buyer GSTIN mismatch: QR contains "${qrData.buyerGstin}", expected "${expectedBuyer}".`
          );
        }
      }

      // Verify Total Amount
      if (qrData.totalValue > 0 && params.totalAmount > 0) {
        const diff = Math.abs(qrData.totalValue - params.totalAmount);
        if (diff > tolerance) {
          discrepancies.push(
            `QR code Total Value mismatch: QR reports ₹${qrData.totalValue.toFixed(2)}, invoice total is ₹${params.totalAmount.toFixed(2)} (diff: ₹${diff.toFixed(2)} > tolerance ₹${tolerance}).`
          );
        }
      }
    }
  }

  const isValid = discrepancies.length === 0;

  return {
    isValid,
    isMandatory,
    irn: cleanIrn || null,
    qrVerified: qrVerified && isValid,
    discrepancies,
  };
}
